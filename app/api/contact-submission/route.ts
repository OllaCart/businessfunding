import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'

export async function POST(request: NextRequest) {
  try {
    console.log('[Contact Submission] Starting contact submission process...')
    
    const body = await request.json()
    const { name, email, phone, subject, message } = body
    
    console.log('[Contact Submission] Received data:', { name, email, phone: phone ? 'provided' : 'not provided', subject: subject || 'none', messageLength: message?.length || 0 })

    if (!name || !email || !message) {
      console.log('[Contact Submission] Missing required fields')
      return NextResponse.json({ error: 'Missing required fields' }, { status: 400 })
    }

    console.log('[Contact Submission] Creating Supabase client...')
    const supabase = await createClient()
    console.log('[Contact Submission] Supabase client created')

    // Save contact submission to database
    console.log('[Contact Submission] Inserting into database...')
    const { data: submission, error: insertError } = await supabase
      .from('contact_submissions')
      .insert([{
        name,
        email,
        phone: phone || null,
        subject: subject || null,
        message
        // created_at is auto-generated by the database
      }])
      .select()
      .single()

    if (insertError) {
      console.error('[Contact Submission] Error saving contact submission:', insertError)
      throw new Error(`Failed to save contact submission: ${insertError.message}`)
    }
    
    console.log('[Contact Submission] Contact submission saved successfully, ID:', submission.id)

    console.log('[Contact Submission] Process completed successfully')
    return NextResponse.json({ 
      success: true, 
      message: 'Contact submission received successfully',
      submissionId: submission.id
    })

  } catch (error) {
    console.error('[Contact Submission] Error processing contact submission:', error)
    return NextResponse.json(
      { error: 'Failed to process contact submission' }, 
      { status: 500 }
    )
  }
}
