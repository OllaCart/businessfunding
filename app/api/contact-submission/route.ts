import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'
import { sendAdminEmail } from '@/lib/email'

export async function POST(request: NextRequest) {
  try {
    console.log('[Contact Submission] Starting contact submission process...')
    
    // Check environment variables
    console.log('[Contact Submission] Environment check:')
    console.log('[Contact Submission] NEXT_PUBLIC_SUPABASE_URL:', process.env.NEXT_PUBLIC_SUPABASE_URL ? 'Set' : 'Not set')
    console.log('[Contact Submission] NEXT_PUBLIC_SUPABASE_ANON_KEY:', process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ? 'Set' : 'Not set')
    console.log('[Contact Submission] GMAIL_USER:', process.env.GMAIL_USER ? 'Set' : 'Not set')
    console.log('[Contact Submission] GMAIL_APP_PASSWORD:', process.env.GMAIL_APP_PASSWORD ? 'Set' : 'Not set')
    
    const body = await request.json()
    const { name, email, phone, subject, message } = body
    
    console.log('[Contact Submission] Received data:', { name, email, phone: phone ? 'provided' : 'not provided', subject: subject || 'none', messageLength: message?.length || 0 })

    if (!name || !email || !message) {
      console.log('[Contact Submission] Missing required fields')
      return NextResponse.json({ error: 'Missing required fields' }, { status: 400 })
    }

    console.log('[Contact Submission] Creating Supabase client...')
    const supabase = await createClient()
    console.log('[Contact Submission] Supabase client created')

    // Save contact submission to database
    console.log('[Contact Submission] Inserting into database...')
    const { data: submission, error: insertError } = await supabase
      .from('contact_submissions')
      .insert([{
        name,
        email,
        phone: phone || null,
        subject: subject || null,
        message
        // created_at is auto-generated by the database
      }])
      .select()
      .single()

    if (insertError) {
      console.error('[Contact Submission] Error saving contact submission:', insertError)
      throw new Error(`Failed to save contact submission: ${insertError.message}`)
    }
    
    console.log('[Contact Submission] Contact submission saved successfully, ID:', submission.id)

    // Send confirmation email to the user
    console.log('[Contact Submission] Sending confirmation email to user...')
    try {
      const userEmailResult = await sendAdminEmail({
        to: email,
        subject: 'Thank you for contacting Marina By-The-Sea',
        content: `Dear ${name},

Thank you for reaching out to Marina By-The-Sea. We have received your message and will get back to you as soon as possible.

Your Message Details:
Subject: ${subject || 'General Inquiry'}
Message: ${message}

We typically respond within 24-48 hours. If you have an urgent matter, please call us at (954) 790-1588.

Best regards,
The Marina By-The-Sea Team`,
        fromName: 'Marina By-The-Sea'
      })
      
      if (!userEmailResult.success) {
        console.error('[Contact Submission] Error sending confirmation email:', userEmailResult.reason || userEmailResult.error)
      } else {
        console.log('[Contact Submission] Confirmation email sent successfully to user')
      }
    } catch (emailError) {
      console.error('[Contact Submission] Error sending confirmation email:', emailError)
      // Don't fail the submission if email fails
    }

    // Send notification to all admins
    console.log('[Contact Submission] Sending admin notifications...')
    try {
      const { data: admins, error: adminError } = await supabase
        .from('admin_profiles')
        .select('email, full_name')
        .eq('role', 'admin')

      if (adminError) {
        console.error('[Contact Submission] Error fetching admin profiles:', adminError)
      } else if (!admins || admins.length === 0) {
        console.warn('[Contact Submission] No admin profiles found')
      } else {
        console.log(`[Contact Submission] Found ${admins.length} admin(s) to notify`)
        
        for (const admin of admins) {
          try {
            console.log(`[Contact Submission] Sending notification to admin: ${admin.email}`)
            const adminEmailResult = await sendAdminEmail({
              to: admin.email,
              subject: `New Contact Form Submission: ${subject || 'General Inquiry'}`,
              content: `A new contact form submission has been received:

Name: ${name}
Email: ${email}
Phone: ${phone || 'Not provided'}
Subject: ${subject || 'General Inquiry'}
Message: ${message}

Submitted: ${new Date().toLocaleString()}

Please respond to this inquiry promptly.`,
              fromName: 'Contact Form System'
            })
            
            if (!adminEmailResult.success) {
              console.error(`[Contact Submission] Failed to send admin notification to ${admin.email}:`, adminEmailResult.reason || adminEmailResult.error)
            } else {
              console.log(`[Contact Submission] Admin notification sent successfully to ${admin.email}`)
            }
          } catch (adminEmailError) {
            console.error(`[Contact Submission] Failed to send admin notification to ${admin.email}:`, adminEmailError)
            // Continue with other admins even if one fails
          }
        }
      }
    } catch (adminNotificationError) {
      console.error('[Contact Submission] Error sending admin notifications:', adminNotificationError)
      // Don't fail the submission if admin notifications fail
    }

    console.log('[Contact Submission] Process completed successfully')
    return NextResponse.json({ 
      success: true, 
      message: 'Contact submission received successfully',
      submissionId: submission.id
    })

  } catch (error) {
    console.error('[Contact Submission] Error processing contact submission:', error)
    return NextResponse.json(
      { error: 'Failed to process contact submission' }, 
      { status: 500 }
    )
  }
}
